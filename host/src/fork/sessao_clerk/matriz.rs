//! Matriz fechada de papéis do acesso remoto num Hub com vínculo: uma entrada por método do
//! despacho (mais as assinaturas `sub:*`), com o papel mínimo. `member` só lê (sem sistema de
//! arquivos do computador nem internos de conta e credencial), conversa e grava as próprias
//! preferências; o resto é `admin` (e `owner`), inclusive a fila compartilhada de envios, o relay
//! do Hub inteiro e as mensagens pessoais do dono. `Nenhum` nega para todos no acesso remoto com
//! vínculo (só no computador do Hub, protocolo de executor, tela remota, credencial de voz).
//! `SemCerca` também nega para todos, até o efeito ter cerca própria ([`sem_cerca`]). Método sem
//! entrada é negado para todos.
use super::vinculo::Papel;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
