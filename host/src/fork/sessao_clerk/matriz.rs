pub(crate) fn minimo(metodo: &str) -> Option<Minimo> {
    MATRIZ.iter().find(|(m, _)| *m == metodo).map(|(_, minimo)| *minimo)
}

pub(crate) fn permitido(papel: Papel, metodo: &str) -> bool {
    match minimo(metodo) {
        Some(Membro) => true,
        Some(Admin) => papel != Papel::Membro,
        Some(Nenhum | SemCerca) | None => false,
    }
}

/// Métodos negados com vínculo até ter cerca; o despacho também os recusa a aparelhos.
pub(crate) fn sem_cerca(metodo: &str) -> bool {
    minimo(metodo) == Some(SemCerca)
}
