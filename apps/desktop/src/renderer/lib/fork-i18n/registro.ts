/** O módulo dono de uma chave: o de prefixo mais longo que a contém; sem nenhum, `null`. */
export function moduloDaChave(chave: string): string | null {
  let dono: { modulo: string; prefixo: string } | null = null
  for (const m of MODULOS) if (chave.startsWith(m.prefixo) && (!dono || m.prefixo.length > dono.prefixo.length)) dono = m
  return dono?.modulo ?? null
}
